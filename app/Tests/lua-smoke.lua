-- Loads the user's thin init.lua (Defaults/init.lua) the way the engine does, against a stub
-- `paneru` table, and checks that microfish.lua reads its settings from MICROFISH_SUPPORT and
-- writes navigator.tsv / navigator.intent to MICROFISH_RUNTIME. No window manager involved.
--
--   luajit app/Tests/lua-smoke.lua <repo>/app/Resources     (exit 0 = pass)
local resources = assert(arg[1], "usage: lua-smoke.lua <Resources dir>")
local root = os.tmpname(); os.remove(root)
local support, runtime = root.."/Support", root.."/Support/Runtime"
assert(os.execute("mkdir -p '"..runtime.."'"))
local function write(path, text) local f = assert(io.open(path, "w")); f:write(text); f:close() end
local function read(path) local f = io.open(path, "r"); if not f then return nil end local t = f:read("*a"); f:close(); return t end

-- What the engine does in bundled mode (see src/bundled.rs).
local function setenv(name, value) require("ffi").cdef("int setenv(const char*, const char*, int);"); require("ffi").C.setenv(name, value, 1) end
setenv("MICROFISH_SUPPORT", support); setenv("MICROFISH_RUNTIME", runtime); setenv("MICROFISH_RESOURCES", resources)

write(support.."/settings.lua", [[-- Generated by the settings panel.
return {options={tab_style="top"}, windows={spacing={horizontal_padding=4}}, swipe={gesture={fingers_count=3}}, marker="from-support"}]])
write(support.."/shortcuts.lua", [[-- Generated shortcuts.
return {rows_enabled=true, row_count=2, bindings={{id="focus_h", chord="alt - h", command="window focus west"}, {id="row_south", chord="alt - j", command="window row south"}, {id="none", chord="", command="x"}}}]])

local handlers, binds, ran, setup_arg = {}, {}, {}, nil
paneru = {
  setup = function(t) setup_arg = t end,
  on = function(event, fn) handlers[event] = fn end,
  bind = function(chord, fn) binds[chord] = fn end,
  run = function(cmd) table.insert(ran, cmd) end,
  query_active = function() return {display_id = 1, virtual_workspace_number = 1, native_workspace_id = 9, focused_window_id = 7} end,
  query_workspaces = function() return {{native_workspace_id = 9, number = 1, windows = {{app_name = "Notes", floating = false}}}} end,
}

-- Exactly what the engine does with the thin file: run it as a chunk.
assert(loadfile(resources.."/Defaults/init.lua"))()

assert(setup_arg and setup_arg.marker == "from-support", "paneru.setup did not get settings.lua from MICROFISH_SUPPORT")
assert(binds["alt - h"] and binds["alt - j"] and not binds[""], "bindings come from shortcuts.lua")
for _, e in ipairs({"window_focused", "swipe", "scroll", "touchpad_up", "mouse_down", "mission_control_exit"}) do assert(handlers[e], e) end

local ws = {
  focused = function() return 7 end,
  columns = function() return {{7}} end,
  column_info = function() return {{tab_bar_height = 0}} end,
  window = function(_, id) return {app_name = "Notes", bundle_id = "com.apple.Notes", title = "Shopping\tlist", frame = {x = 0, y = 0, width = 800, height = 600}} end,
}
handlers.window_focused({}, ws)
local tsv = assert(read(runtime.."/navigator.tsv"), "navigator.tsv was not written to MICROFISH_RUNTIME")
assert(tsv:match("^7\t1\t1\n7\t1\tNotes\tcom%.apple%.Notes\tShopping list\t0\t7"), tsv)
assert(tsv:find("#rows\t1\t2", 1, true) and tsv:find("#row\t1\t1\tNotes", 1, true), tsv)
assert(not read(runtime.."/navigator.tsv.tmp"), "temp file left behind")

binds["alt - j"](ws)
assert(read(runtime.."/navigator.intent") == "row", "navigator.intent")
assert(ran[#ran] == "window row south", ran[#ran])

handlers.mouse_down()
assert(read(runtime.."/navigator.intent") == "dismiss")
handlers.touchpad_down()
handlers.swipe({fingers = 3}, ws)
assert(read(runtime.."/navigator.intent") == "swipe")
handlers.touchpad_up({}, ws)
assert(read(runtime.."/navigator.intent") == "lift")

os.execute("rm -rf '"..root.."'")
print("lua-smoke: ok (microfish.lua loads, reads MICROFISH_SUPPORT, writes MICROFISH_RUNTIME)")
